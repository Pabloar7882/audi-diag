"""Build the shared group metadata view from the local, bounded .LBL inventory.

The scan contributes candidate counts and source names only. It cannot create a
decoder or change the physical group allow-list.
"""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from diagnostic_groups import SUPPORTED_GROUP_IDS, default_afn_groups  # noqa: E402
from label_catalog import scan_labels  # noqa: E402


STATUS_TO_C = {
    "ACTIVE_ALLOWED": "FIS_CATALOG_ACTIVE_ALLOWED",
    "IMPLEMENTED_UNVERIFIED": "FIS_CATALOG_IMPLEMENTED_UNVERIFIED",
    "METADATA_ONLY": "FIS_CATALOG_METADATA_ONLY",
    "UNKNOWN": "FIS_CATALOG_UNKNOWN",
    "UNSUPPORTED_CONFIRMED": "FIS_CATALOG_UNSUPPORTED_CONFIRMED",
}


def build_group_records(labels_root: Path, base_catalog: dict) -> list[dict]:
    inventory = scan_labels(labels_root)
    field_counts: Counter[int] = Counter()
    source_documents: dict[int, list] = defaultdict(list)
    for document in inventory.files:
        if not document.loaded:
            continue
        for group_id in document.groups:
            source_documents[group_id].append(document)
        field_counts.update(field.group_id for field in document.fields)

    active_names = {
        group.group_id: group.label
        for group in default_afn_groups()
        if group.group_id in SUPPORTED_GROUP_IDS
    }
    result = []
    for group_id in range(256):
        if group_id in SUPPORTED_GROUP_IDS:
            status = "ACTIVE_ALLOWED"
            source_refs = [{"file": "diagnostic_groups.py", "line": None}]
            name = active_names[group_id]
            description = "Grupo permitido pela política física independente; os valores KW1281 continuam sem descodificação validada."
        elif source_documents.get(group_id):
            status = "METADATA_ONLY"
            sources = sorted(source_documents[group_id], key=lambda item: item.relative_path.casefold())
            source_refs = [
                {"file": item.relative_path.replace("\\", "/"), "line": None, "sha256": item.sha256}
                for item in sources[:5]
            ]
            name = f"Grupo {group_id:03d}"
            description = "Há labels para este grupo no inventário local; compatibilidade AFN e fórmulas não confirmadas."
        else:
            status = "UNKNOWN"
            source_refs = []
            name = f"Grupo {group_id:03d}"
            description = None

        result.append({
            "group_id": group_id,
            "name": name,
            "description": description,
            "status": status,
            "metadata_candidate_count": field_counts[group_id],
            "metadata_source_count": len(source_documents.get(group_id, ())),
            "source_refs": source_refs,
        })

    # Keep the parser's measured inventory close to its generated metadata.
    base_catalog["label_inventory"] = {
        "files_scanned": len(inventory.files),
        "files_loaded": sum(1 for item in inventory.files if item.loaded),
        "field_rows": sum(field_counts.values()),
        "warning_count": len(inventory.warnings),
        "notes": [
            "Counts aggregate labels across ECU variants and do not establish AFN compatibility.",
            "Label metadata never changes physical read permission or decoder definitions.",
        ],
    }
    return result


def write_catalog(labels_root: Path, catalog_path: Path, c_path: Path) -> None:
    document = json.loads(catalog_path.read_text(encoding="utf-8"))
    groups = build_group_records(labels_root, document)
    document["groups"] = groups
    catalog_path.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    rows = ",\n".join(
        f"    {{{row['group_id']}u, {STATUS_TO_C[row['status']]}, {row['metadata_candidate_count']}u}}"
        for row in groups
    )
    c_path.write_text(
        "/* Generated by tools/build_sensor_catalog.py; do not edit by hand. */\n"
        "static const fis_catalog_entry FIS_GROUP_CATALOG[256] = {\n"
        f"{rows}\n"
        "};\n",
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--labels-root", type=Path, default=ROOT / "Labels")
    parser.add_argument("--catalog", type=Path, default=ROOT / "data" / "sensor_catalog.v1.json")
    parser.add_argument("--c-output", type=Path, default=ROOT / "firmware" / "esp32" / "src" / "fis_group_catalog.inc")
    args = parser.parse_args()
    write_catalog(args.labels_root, args.catalog, args.c_output)


if __name__ == "__main__":
    main()
